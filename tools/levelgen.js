// Dev tool: builds the ASCII level grids from geometry code and writes
// src/levels/levelN.js. Run: node tools/levelgen.js
//
// Jump reference (CFG): apex = 0.9 + 2.3 * waxFrac tiles.
//   1-tile step: always.  2-tile ledge: waxFrac >= ~0.5.  3-tile: only near full.
//   Gap at equal height: 3 tiles always, 4 tiles needs waxFrac >= ~0.6, 5+ needs blobs.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'levels');

class Grid {
  constructor(w, h) {
    this.w = w; this.h = h;
    this.r = Array.from({ length: h }, () => Array(w).fill('.'));
    this.entities = [];
  }
  put(x, y, c) { if (x >= 0 && y >= 0 && x < this.w && y < this.h) this.r[y][x] = c; return this; }
  rect(x0, y0, x1, y1, c = '#') {
    for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) this.put(x, y, c);
    return this;
  }
  // solid from row `top` to the bottom
  ground(x0, x1, top, c = '#') { return this.rect(x0, top, x1, this.h - 1, c); }
  clear(x0, y0, x1, y1) { return this.rect(x0, y0, x1, y1, '.'); }
  plat(x0, x1, y) { return this.rect(x0, y, x1, y, '='); }
  // fill only empty cells (wind markers)
  fill(x0, y0, x1, y1, c) {
    for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) if (this.r[y]?.[x] === '.') this.r[y][x] = c;
    return this;
  }
  sign(x, y, text) { this.entities.push({ type: 'sign', x, y, text }); return this; }
  rows() { return this.r.map((row) => row.join('')); }
}

const DEFS = {};
function define(key, meta, g) { DEFS[key] = { meta, g }; }

function write(n, meta, g) {
  const keeps = g.rows().join('').split('K').length - 1;
  if (keeps !== 1) throw new Error(`${meta.name}: expected 1 keepsake, found ${keeps}`);
  const body = [
    `// Level ${n}: ${meta.name}. Generated by tools/levelgen.js.`,
    `// Legend: . empty  # stone  = one-way  ~ drip emitter  S spawn  T torch  P pumpkin  L lantern`,
    `//         G goal  w cobweb  f fuse  g gate  W wind  o plate  d door  h hay  b barrel  k crate  n banner`,
    `//         K keepsake  l lamp`,
    `export default {`,
    `  name: ${JSON.stringify(meta.name)},`,
    `  hint: ${JSON.stringify(meta.hint)},`,
    ...(meta.par ? [`  par: ${JSON.stringify(meta.par)},`] : []),
    ...Object.entries(meta.extra || {}).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`),
    `  tiles: [`,
    ...g.rows().map((r) => `    '${r}',`),
    `  ],`,
    `  entities: [`,
    ...g.entities.map((e) => `    ${JSON.stringify(e)},`),
    `  ],`,
    `};`,
    ``,
  ].join('\n');
  writeFileSync(join(OUT, `level${n}.js`), body);
  console.log(`level${n}.js  ${g.w}x${g.h}`);
}

